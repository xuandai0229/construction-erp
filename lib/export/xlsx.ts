type WorksheetRow = Array<string | number | Date | null | undefined>;

export interface XlsxSheetInput {
  sheetName: string;
  title: string;
  metadata: Array<[string, string]>;
  headers: string[];
  rows: WorksheetRow[];
  totals?: WorksheetRow;
}

function xmlEscape(value: unknown) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function columnName(index: number) {
  let name = "";
  let current = index + 1;
  while (current > 0) {
    const rem = (current - 1) % 26;
    name = String.fromCharCode(65 + rem) + name;
    current = Math.floor((current - 1) / 26);
  }
  return name;
}

function cellXml(value: unknown, rowIndex: number, colIndex: number, style = 0) {
  const ref = `${columnName(colIndex)}${rowIndex}`;
  const styleAttr = style ? ` s="${style}"` : "";
  if (typeof value === "number" && Number.isFinite(value)) {
    return `<c r="${ref}"${styleAttr}><v>${value}</v></c>`;
  }
  if (value instanceof Date) {
    return `<c r="${ref}" t="inlineStr"${styleAttr}><is><t>${xmlEscape(value.toLocaleDateString("vi-VN"))}</t></is></c>`;
  }
  return `<c r="${ref}" t="inlineStr"${styleAttr}><is><t>${xmlEscape(value)}</t></is></c>`;
}

function rowXml(values: WorksheetRow, rowIndex: number, style = 0) {
  return `<row r="${rowIndex}">${values.map((value, colIndex) => cellXml(value, rowIndex, colIndex, style)).join("")}</row>`;
}

function worksheetXml(input: XlsxSheetInput) {
  const allRows: string[] = [];
  let rowIndex = 1;

  allRows.push(rowXml([input.title], rowIndex++, 1));
  for (const [label, value] of input.metadata) {
    allRows.push(rowXml([label, value], rowIndex++, 0));
  }
  allRows.push(rowXml([], rowIndex++));
  allRows.push(rowXml(input.headers, rowIndex++, 2));
  for (const row of input.rows) {
    allRows.push(rowXml(row, rowIndex++, 0));
  }
  if (input.totals) {
    allRows.push(rowXml(input.totals, rowIndex++, 3));
  }

  const colCount = Math.max(input.headers.length, 1);
  const cols = Array.from({ length: colCount }, (_, index) => {
    const width = index === 0 ? 12 : index < 3 ? 28 : 18;
    return `<col min="${index + 1}" max="${index + 1}" width="${width}" customWidth="1"/>`;
  }).join("");

  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <sheetViews><sheetView workbookViewId="0"><pane ySplit="${input.metadata.length + 3}" topLeftCell="A${input.metadata.length + 4}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
  <sheetFormatPr defaultRowHeight="18"/>
  <cols>${cols}</cols>
  <sheetData>${allRows.join("")}</sheetData>
  <pageMargins left="0.3" right="0.3" top="0.5" bottom="0.5" header="0.2" footer="0.2"/>
  <pageSetup paperSize="9" orientation="landscape" fitToWidth="1" fitToHeight="0"/>
</worksheet>`;
}

